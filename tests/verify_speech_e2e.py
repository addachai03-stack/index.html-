#!/usr/bin/env python3
"""Original speech-fixture E2E check. Only uses locally generated synthetic media.

Does not retrieve social videos or use private user footage. It exercises
studio.main() after the source-download boundary, then FFprobe and creator copy.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
from unittest.mock import patch

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import studio


def command(args, timeout=150):
    p=subprocess.run(args,capture_output=True,text=True,timeout=timeout)
    if p.returncode:
        raise RuntimeError(args[0]+": "+(p.stderr or p.stdout)[-1800:])
    return p.stdout


def main():
    message=(
        "Did you know a camera can tell a fascinating story? "
        "The incredible secret is that daylight changes how colors look. "
        "A mountain landscape reveals an amazing surprise when the sun rises. "
        "Here is another important fact about making videos. "
        "Speaking clearly helps viewers understand each interesting moment. "
        "We are checking original synthetic English speech, synchronized captions, "
        "good hooks, descriptions, and topic related hashtags. "
        "Watch this amazing science explanation and listen to the surprising secret. "
        "This is only an original demo for testing video editing and speech detection."
    )
    with tempfile.TemporaryDirectory() as temp:
        root=Path(temp)
        wav=root/"speech.wav"
        source=root/"original_test_video.mp4"
        command(["espeak","-v","en-us","-s","145","-a","190","-w",str(wav),message])
        # Repeating our own spoken waveform gives both 30s windows real speech.
        command(["ffmpeg","-nostdin","-hide_banner","-loglevel","error","-y",
                 "-f","lavfi","-i","testsrc2=size=1280x720:rate=12",
                 "-stream_loop","-1","-i",str(wav),
                 "-t","61.0","-c:v","libx264","-preset","ultrafast",
                 "-crf","33","-pix_fmt","yuv420p","-c:a","aac",
                 "-b:a","96k","-shortest",str(source)],timeout=150)
        out=Path(os.environ.get("GITHUB_WORKSPACE",Path.cwd()))/"speech_e2e_output"
        out.mkdir(parents=True,exist_ok=True)
        sys.argv=["studio.py","--url","https://example.com/original-synthetic-test.mp4",
                  "--clips","2","--min-seconds","30","--max-seconds","30",
                  "--style","engagement","--crop","center",
                  "--language","en","--caption-script","original",
                  "--caption-style","classic","--rights-confirmed",
                  "--output",str(out)]
        # Patch only the URL fetch boundary to use video generated by this CI job.
        # The real renderer engine, audio recognition, scoring, crop, captions,
        # MP4 encoder, Creator Pack and manifest all execute unchanged.
        with patch.object(studio,"validate_url",return_value="https://example.com/original-synthetic-test.mp4"),patch.object(studio,"download",return_value=source):
            status=studio.main()
        report=json.loads((out/"report.json").read_text(encoding="utf-8"))
        if status!=0:
            raise RuntimeError("Renderer returned failure: "+str(report))
        manifest=json.loads((out/"manifest.json").read_text(encoding="utf-8"))
        pack=json.loads((out/"Creator_Pack.json").read_text(encoding="utf-8"))
        if len(manifest["clips"])!=2 or len(pack["clips"])!=2:
            raise AssertionError("Exactly two rendered clips and two posting packs required")
        validations=[]
        for i, clip in enumerate(manifest["clips"],1):
            mp4=out/clip["mp4"]
            info=json.loads(command(["ffprobe","-v","error",
                "-show_entries","format=duration:stream=codec_type,width,height",
                "-of","json",str(mp4)]))
            videos=[s for s in info["streams"] if s["codec_type"]=="video"]
            if len(videos)!=1 or videos[0]["width"]!=720 or videos[0]["height"]!=1280:
                raise AssertionError("Expected exactly one 720x1280 video stream")
            duration=float(info["format"]["duration"])
            if not 29.9<=duration<=30.1:
                raise AssertionError("Expected 30s encoded MP4; actual "+str(duration))
            if not clip.get("captions") or not (out/clip["captions"]).is_file():
                raise AssertionError("Speech-recognition subtitles missing in Short #"+str(i))
            speech=clip["transcript"]
            if not speech.strip():
                raise AssertionError("ASR recognized no speech in clip #"+str(i))
            c=clip["creator"]
            if not c["hook_options"] or not c["description"].strip() or not c["caption"].strip() or not c["hashtags"].strip():
                raise AssertionError("Creator Pack content missing for clip #"+str(i))
            if c["topic_keywords"]=="":
                raise AssertionError("Expected topic-derived keywords from original spoken demo")
            if not (out/("short_%02d_post.txt"%i)).is_file():
                raise AssertionError("Missing per-clip post text")
            validations.append({"file":clip["mp4"],"duration_seconds":duration,
                "resolution":"720x1280","speech_characters":len(speech),
                "srt":clip["captions"],"hook_options":c["hook_options"],
                "hashtags":c["hashtags"]})
        result={"status":"pass","fixture":"original synthetic speech via espeak",
            "real_video_download_tested":False,
            "video_download":"separately validated with publicly licensed media in Issue #7",
            "whisper_asr":manifest.get("asr"),
            "clips":validations,
            "note":"Burned-in subtitles sent to FFmpeg; visual subtitle pixel-level comparison not included."}
        (out/"speech_e2e_report.json").write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding="utf-8")
        print(json.dumps(result,indent=2,ensure_ascii=False))
        print("PASS: Actual spoken audio → Whisper ASR → 2 exact 30s portrait MP4s → SRT captions + Creator Pack")


if __name__=="__main__":
    main()
