/* CutNova Auto Live: real, read-only results from a configured GitHub Actions monitor.
 * No viewer credentials, tokens, video downloading, background browser timers or DM.
 */
(function(root){
  "use strict";
  const KEY = "cutnova-autolive-target-v1";
  function normalizeTarget(platform, channel){
    platform = String(platform || "").trim().toLowerCase();
    channel = String(channel || "").trim();
    if(platform === "twitch" && /^[a-zA-Z0-9_]{3,25}$/.test(channel))
      return {platform,channel:channel.toLowerCase()};
    if(platform === "youtube" && (/^@[a-zA-Z0-9._-]{3,30}$/.test(channel)||/^UC[a-zA-Z0-9_-]{22}$/.test(channel)))
      return {platform,channel};
    throw Error("Enter a Twitch username or YouTube @handle / UC channel ID.");
  }
  function safeClipURL(uri){
    try{
      const u = new URL(uri);
      return u.protocol === "https:" && (u.hostname === "clips.twitch.tv" ||
        u.hostname === "twitch.tv" || u.hostname === "www.twitch.tv") ? u.href : null;
    }catch{return null;}
  }
  function freshness(status, when=Date.now()){
    const checked=Date.parse(status?.checked_at||"");
    return Number.isFinite(checked)&&Math.abs(when-checked)<=90*60*1000 ? "current" : "stale";
  }
  if(typeof module !== "undefined" && module.exports){
    module.exports={normalizeTarget,safeClipURL,freshness};
    return;
  }
  const d=root.document;
  if(!d)return;
  const by=id=>d.getElementById(id);
  const platform=by("live-platform"),channel=by("live-channel"),save=by("live-save"),
    refresh=by("live-refresh"),rights=by("live-rights"),message=by("live-feedback"),
    state=by("live-state"),checked=by("live-checked"),title=by("live-title"),
    details=by("live-details"),clips=by("live-clips"),clipFeedback=by("live-clip-feedback"),
    streamLink=by("live-open-stream");
  if(!save||!platform||!channel||!refresh)return;
  let selected=null,busy=false;
  const say=x=>{message.textContent=x};
  const clipSay=x=>{clipFeedback.textContent=x};
  function restore(){
    try{
      const entry=JSON.parse(root.localStorage.getItem(KEY)||"null");
      if(entry){selected=normalizeTarget(entry.platform,entry.channel);
        platform.value=selected.platform;channel.value=selected.channel;}
    }catch{/* Storage may be disabled. Manual entry still works. */}
  }
  function updateState(value,tone){
    state.textContent=value;state.className="status-big"+(tone?" "+tone:"");
  }
  function reset(text){
    updateState("NOT CONNECTED");checked.textContent=text||"No API status loaded.";
    title.textContent="NO STREAM DATA";details.textContent="No verified live session.";
    streamLink.hidden=true;clips.replaceChildren();
    const p=d.createElement("p");p.className="mini";p.textContent="No verified public clips for this selected channel.";clips.append(p);
    root.dispatchEvent(new CustomEvent("cutnova:live-status",{detail:{result:null,target:null}}));
  }
  function showClips(items, target){
    clips.replaceChildren();
    const valid=Array.isArray(items)?items.filter(c=>safeClipURL(c.url)).slice(0,12):[];
    if(!valid.length){
      const p=d.createElement("p");p.className="mini";
      p.textContent=target.platform==="youtube"?"YouTube live metadata does not include ready-made clip results.":"No official public Twitch clips found in the last 48 hours.";
      clips.append(p);return;
    }
    valid.forEach((clip,index)=>{
      const card=d.createElement("article");card.className="clip";
      const top=d.createElement("div");top.className="clip-top";
      const name=d.createElement("h3");name.className="clip-title";name.textContent=String(clip.title||"Untitled Twitch clip").slice(0,140);
      const badge=d.createElement("span");badge.className="clip-num";badge.textContent="#"+(index+1)+" · "+Math.max(0,Math.floor(Number(clip.view_count)||0)).toLocaleString()+" VIEWS";
      top.append(name,badge);
      const info=d.createElement("p");info.className="mini";info.textContent="Existing official Twitch clip · "+Math.round(Number(clip.duration)||0)+"s · Not generated by CutNova";
      const actions=d.createElement("div");actions.className="clip-actions";
      const url=safeClipURL(clip.url);
      const link=d.createElement("a");link.className="btn";link.href=url;link.target="_blank";link.rel="noopener noreferrer";
      link.textContent="OPEN ON TWITCH ↗";
      const copy=d.createElement("button");copy.className="btn";copy.type="button";copy.textContent="COPY POST DRAFT";
      copy.addEventListener("click",async()=>{
        if(!rights.checked){clipSay("Please confirm you have editing/reposting rights first. A public clip URL is not permission.");return;}
        const draft=String(clip.title||"Stream moment").slice(0,140)+"\n"+
          "Original clip: "+url+"\n#livestream #clip #shorts\n\nVerify credits and rights before posting.";
        try{
          if(!root.navigator?.clipboard?.writeText)throw Error("Clipboard unavailable");
          await root.navigator.clipboard.writeText(draft);clipSay("Draft text copied. No upload or automatic post.");
        }catch{clipSay("Clipboard is unavailable here. Use the official clip link and copy manually.");}
      });
      actions.append(link,copy);card.append(top,info,actions);clips.append(card);
    });
  }
  function safeStreamURL(url,target){
    try{
      const u=new URL(url);
      const hosts=target.platform==="twitch"?["twitch.tv","www.twitch.tv"]:["youtube.com","www.youtube.com"];
      return u.protocol==="https:"&&hosts.includes(u.hostname)?u.href:null;
    }catch{return null;}
  }
  function render(result,target){
    if(result.schema_version!==1)throw Error("Unsupported monitor status format.");
    const report=normalizeTarget(result.platform,result.channel);
    if(report.platform!==target.platform||report.channel!==target.channel){
      reset("This repository is monitoring "+report.platform+" / "+report.channel+", not your saved target.");
      updateState("OTHER CHANNEL");say("Your local target differs from GitHub Actions settings. Set the same platform/channel under repository Variables; then run the monitor.");
      return;
    }
    const when=Date.parse(result.checked_at||"");
    checked.textContent=Number.isFinite(when)?"Last monitor check: "+new Date(when).toLocaleString():"Monitor timestamp unavailable.";
    const fresh=freshness(result)==="current";
    if(!fresh){updateState("STALE CHECK","error");say("Monitor output is older than 90 minutes. GitHub workflow may be paused. Do not rely on an old LIVE badge.");}
    else{
      const code=String(result.state||"UNKNOWN").toUpperCase();
      updateState(code,code==="LIVE"?"live":code==="API_ERROR"||code==="INVALID_CHANNEL"?"error":"");
      say(code==="LIVE"?"Official API reported LIVE at the checked time (not a continuous real-time stream connection).":
          code==="OFFLINE"?"Official API reported offline at the checked time. Monitoring resumes on the next scheduled run.":
          code==="NOT_CONFIGURED"?"GitHub Actions credentials or target configuration are missing. See OWNER SETUP.":"Monitor result: "+code+". Check owner settings or Actions logs.");
    }
    const live=result.stream&&result.state==="LIVE"?result.stream:null;
    title.textContent=live?String(live.title||"LIVE STREAM").slice(0,140):"NO ACTIVE STREAM";
    details.textContent=live?(target.platform.toUpperCase()+" · "+String(live.game_name||"Public stream").slice(0,80)+" · "+
      (Number.isFinite(Number(live.viewer_count))&&live.viewer_count!==null?Number(live.viewer_count).toLocaleString()+" viewers":"viewer count unavailable")):
      ("No active public stream in the last official check. Reconnects are checked again on the next schedule. Resumed sessions detected: "+Math.max(0,Number(result.restart_count)||0));
    const href=live?safeStreamURL(live.url,target):null;
    if(href){streamLink.href=href;streamLink.hidden=false;}else streamLink.hidden=true;
    showClips(result.clips,target);
    root.dispatchEvent(new CustomEvent("cutnova:live-status",{detail:{result,target}}));
  }
  function chosen(){
    const next=normalizeTarget(platform.value,channel.value);
    return next;
  }
  save.addEventListener("click",()=>{
    try{
      selected=chosen();
      try{root.localStorage.setItem(KEY,JSON.stringify(selected));say("Saved on this phone. Configure the SAME target in GitHub Actions to start scheduled server checks. No stream recording started.");}
      catch{say("Target selected for this tab; browser storage unavailable. Configure GitHub Actions separately.");}
      reset("Channel selected. Tap CHECK LAST MONITOR RESULT to fetch the last official check.");
    }catch(error){say(error.message);}
  });
  refresh.addEventListener("click",()=>load());
  async function load(){
    if(busy)return;
    let target;
    try{target=chosen();selected=target;}
    catch(error){say(error.message);return;}
    busy=true;refresh.disabled=true;
    say("Reading the latest scheduled status from this website. Not contacting Twitch/YouTube directly...");
    try{
      // GITHUB_TOKEN-created commits do not start GitHub Pages rebuilds.
      // Read the public repository's latest JSON rather than a stale Pages copy.
      const latest="https://raw.githubusercontent.com/addachai03-stack/index.html-/main/autolive/status.json";
      let response;
      try{
        const controller=new AbortController();
        const timer=setTimeout(()=>controller.abort(),8000);
        try{response=await fetch(latest+"?check="+Date.now(),{
          cache:"no-store",credentials:"omit",signal:controller.signal
        });}finally{clearTimeout(timer);}
        if(!response.ok)throw Error("Raw GitHub status HTTP "+response.status);
      }catch(_){
        // Fallback only: Pages may have an old state, which freshness() marks.
        response=await fetch("./autolive/status.json",{cache:"no-store",credentials:"omit"});
      }
      if(!response.ok)throw Error("Monitor has not published a result (HTTP "+response.status+").");
      const data=await response.json();
      if(!data||typeof data!=="object")throw Error("Invalid monitor response");
      if(data.state==="NOT_CONFIGURED"&&!data.channel){
        reset("No GitHub channel/credentials configured.");
        updateState("SETUP REQUIRED");say("Open OWNER SETUP below. Enter repository variables/secrets and run the GitHub workflow.");return;
      }
      render(data,target);
    }catch(error){reset("Could not load an official monitor result.");updateState("NOT VERIFIED","error");say(String(error?.message||"Monitor unavailable").slice(0,220));}
    finally{busy=false;refresh.disabled=false;}
  }
  restore();reset("Waiting for an official check.");
  if(selected)load();
})(typeof window!=="undefined"?window:null);
